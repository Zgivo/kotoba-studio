function scriptType(japanese: string): JapaneseScriptType {
  const hasKanji = /[一-龯々]/u.test(japanese);
  const hasHiragana = /[ぁ-ゖ]/u.test(japanese);
  const hasKatakana = /[ァ-ヺー]/u.test(japanese);
  const count = [hasKanji, hasHiragana, hasKatakana].filter(Boolean).length;
  if (count > 1) return 'mixed';
  if (hasKanji) return 'kanji';
  if (hasKatakana) return 'katakana';
  return 'hiragana';
}

